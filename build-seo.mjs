const stripTags = s => s.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const decode = s => s.replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"');
const attr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// pull the visible FAQ straight out of the page
function readFaq(html) {
  const items = [];
  const re = /<button class="faq__q"[^>]*>([\s\S]*?)<span class="faq__ic"[\s\S]*?<div class="faq__a"><div>([\s\S]*?)<\/div><\/div>/g;
  let m;
  while ((m = re.exec(html))) {
    items.push({ q: decode(stripTags(m[1])), a: decode(stripTags(m[2])) });
  }
  return items;
}

