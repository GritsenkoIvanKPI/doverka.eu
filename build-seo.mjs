const MARK_OPEN = '<!-- ===== SEO / social / icons — generated by build-seo.mjs ===== -->';
const MARK_CLOSE = '<!-- ===== /SEO ===== -->';
const LD_OPEN = '<!-- ===== structured data — generated by build-seo.mjs ===== -->';
